"""Built-in seed catalog of the «Библиотека HR» (safe provisioning).

On a clean installation the library must not be empty: a new HR should open
the section and immediately find useful, printable material. This module
provisions a starter catalog of **impersonal, generalized** materials written
for this product — they are inspired by the owner's methodical base but copy
nothing: no company names, no cities, no real phone numbers or names, no
figures that go stale.

Safety and idempotency rules:

* a seed material is an ordinary :class:`app.models.DocumentTemplate` with
  one published version; it is marked with a unique ``seed_key``;
* :func:`seed_library` runs at application startup (like the administrator
  bootstrap) and **never touches an existing row**: if a ``seed_key`` already
  exists — even renamed, republished or archived by the owner — it is skipped.
  Re-running the seed therefore cannot create duplicates;
* content is validated by the same pipeline as user input
  (:mod:`app.template_render`), so a seed body can never contain markup the
  editor would reject;
* the seed is provisioning, not a user action: unlike template operations it
  writes no audit rows (the bootstrap does not either), and no user content
  or personal data is involved;
* if the installation has no users yet (a production start before the first
  administrator exists), the seed is skipped and happens on the next start
  after an administrator appears, because a version needs an author.

The owner replaces seed materials with approved documents through «Управление
материалами» (import from DOCX/TXT, then publish) — no code changes needed;
see ``docs/library.md``.
"""

